const resolveBeerStyle = (name) => {
  const normalized = String(name || '').toLowerCase();
  for (const [key, words] of STYLE_KEYWORDS) {
    if (words.some((word) => normalized.includes(word))) return key;
  }
  return 'beer';
};

// Оставлены поля ing/cond для совместимости со старыми вызовами.
const withAliases = (data) => ({
  ...data,
  ing: data.ingredients,
  cond: data.technology,
});

export function getComposition(product) {
  const isString = typeof product === 'string';
  const category = isString ? product : (product?.category ?? '');
  const name = isString ? '' : (product?.name ?? '');

  if (category && category !== 'Пиво') {
    return withAliases(CATEGORY_COMPOSITION[category] || CATEGORY_COMPOSITION.default);
  }

  if (!category) {
    const normalized = String(name).toLowerCase();
    const guessed = Object.keys(CATEGORY_COMPOSITION)
      .filter((key) => key !== 'default')
      .find((key) => normalized.includes(key.toLowerCase()));
    if (guessed) return withAliases(CATEGORY_COMPOSITION[guessed]);
  }

  return withAliases(BEER_STYLES[resolveBeerStyle(name)] || BEER_STYLES.beer);
}
